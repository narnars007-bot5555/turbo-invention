                    "Недостаточный угол главного плана phi или режущий радиус вершины резца слишком велик",
                    "Завышенная скорость резания Vc при недостаточной подаче"
                ),
                correctiveActions = listOf(
                    "Уменьшить вылет инструмента и детали, применить антивибрационную оправку (Silent Tools / Carbide shank)",
                    "Применить резцы с углом в плане 90° (KOR-90°) для направленности сил резания вдоль оси детали",
                    "Снизить скорость резания Vc на 20-30% или изменить обороты шпинделя (Spindle Speed Variation)",
                    "Увеличить подачу f для вывода стружкообразования из резонансной зоны"
                )
            ),
            DefectInfo(
                defectName = "Прижоги и микротрещины при шлифовании (Grinding Burn)",
                category = "Шлифование и финишная обработка",
                probableCauses = listOf(
                    "Засаливание или затупление абразивного круга (абразив теряет самозатачиваемость)",
                    "Слишком высокая скорость детали Vw или избыточная глубина шлифования ae",
                    "Недостаточное или некорректно направленное охлаждение СОЖ в зону резания",
                    "Слишком твердый круг (например, M или N вместо J или K)"
                ),
                correctiveActions = listOf(
                    "Выполнить правку круга алмазным карандашом с увеличенным шагом правки Ud",
                    "Перейти на более мягкую структуру или марку круга (например, 25A 60 J V)",
                    "Увеличить расход и давление подачи СОЖ, направить сопло точно в клин шлифования",
                    "Уменьшить глубину прохода ae и скорректировать скорость детали Vw"
                )
            ),
            DefectInfo(
                defectName = "Сколы и выкрашивание пластин (Insert Chipping / Thermal Cracks)",
                category = "Режущий инструмент ISO 1832",
                probableCauses = listOf(
                    "Прерывистое резание с термическими ударами при неравномерной подаче СОЖ",
                    "Слишком хрупкий сплав пластины (например, P10/K10 вместо P30/M20)",
                    "Налипание материала (нарост на режущей кромке BUE)",
                    "Недостаточный радиус вершины резца r_eps или слишком слабая геометрия стружколома"
                ),
                correctiveActions = listOf(
                    "При прерывистом резании отключить СОЖ (сухое точение) или обеспечивать обильное бесперебойное охлаждение",
                    "Заменить сплав на более вязкий (P25-P40 с PVD/CVD покрытием)",
                    "Увеличить скорость резания Vc для предотвращения наростообразования",
                    "Применить пластину с большей толщиной и упрочненной фаской (отрицательный стружколом)"
                )
            ),
            DefectInfo(
                defectName = "Подрез ножки зуба (Gear Tooth Undercutting)",
                category = "Зубообработка (Зубофрезерование / Зубодолбление)",
                probableCauses = listOf(
                    "Число зубьев колеса меньше критического z < 17 (при угле профиля alpha = 20°)",
                    "Некорректное смещение исходного контура (высотный модификатор x = 0)",
                    "Завышенная глубина врезания долбяка или червячной фрезы"
                ),
                correctiveActions = listOf(
                    "Ввести положительное смещение исходного контура x > 0 (высотная коррекция)",
                    "Использовать инструмент с модифицированной головкой (протуберанцем)",
                    "Пересчитать геометрию зацепления с увеличением угла профиля alpha до 22.5° или 25°"
                )
            )
        )
    }

    fun searchDefects(query: String): List<DefectInfo> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return getAllDefects()
        return getAllDefects().filter {
            it.defectName.lowercase().contains(q) ||
                    it.category.lowercase().contains(q) ||
                    it.probableCauses.any { c -> c.lowercase().contains(q) } ||
                    it.correctiveActions.any { a -> a.lowercase().contains(q) }
        }
    }
}
